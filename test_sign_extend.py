import pytest
from adrp_decode import sign_extend

@pytest.mark.parametrize("value,n,m,expected", [
  # Sign bit is 0, should not change
  (0b00000000000000000000000000000000,  2,  5, 0b00000000000000000000000000000000),
  (0b00000000000000000000000000000001,  2,  5, 0b00000000000000000000000000000001),
  (0b00000000000000111111111111111111, 19, 32, 0b00000000000000111111111111111111),
  # Sign bit is 1, should extend
  (0b00000000000000000000000000000010,  2,  5, 0b00000000000000000000000000011110),
  (0b00000000000000000000000000000011,  2,  5, 0b00000000000000000000000000011111),
  (0b00000000000001000000000000000000, 19, 32, 0b11111111111111000000000000000000),
  # All bits set, sign bit is 1
  (0b00000000000001111111111111111111, 19, 32, 0b11111111111111111111111111111111),
  # n=1, sign bit is value itself
  (0b00000000000000000000000000000001,  1,  8, 0b00000000000000000000000011111111),
  (0b00000000000000000000000000000000,  1,  8, 0b00000000000000000000000000000000),
  # m<n, should reduce
  (0b00000000000000000000000000001111,  6,  3, 0b00000000000000000000000000000011),
  (0b00000000000000000000000000111111,  6,  3, 0b00000000000000000000000000000111),
  # m<n, n=1, should reduce to sign bit
  (0b00000000000000000000000000001111,  6,  1, 0b00000000000000000000000000000000),
  (0b00000000000000000000000000111111,  6,  1, 0b00000000000000000000000000000001),
  # m=0, should, reduce to nothing
  (0b00000000000000000000000000100000,  7,  0, 0b00000000000000000000000000000000),
  (0b00000000000000000000000000000000,  7,  0, 0b00000000000000000000000000000000),
])
def test_sign_extend(value, n, m, expected):
  actual = format(sign_extend(value, n, m) & 0xFFFFFFFFFFFFFFFF, '032b')
  expected = format(expected & 0xFFFFFFFFFFFFFFFF, '032b')
  value = format(value & 0xFFFFFFFFFFFFFFFF, '032b')
  print(f"n: {n}, m: {m}\nvalue:    {value}\nexpected: {expected}\nactual:   {actual}")
  assert actual == expected
